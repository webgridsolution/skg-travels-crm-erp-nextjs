CREATE TABLE IF NOT EXISTS route_seo_pages (
  id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
  company_id BIGINT UNSIGNED NOT NULL,
  city_name VARCHAR(100) NOT NULL,
  city_slug VARCHAR(120) NOT NULL,
  from_city VARCHAR(100) NOT NULL,
  to_city VARCHAR(100) NOT NULL,
  slug VARCHAR(190) NOT NULL,
  h1_title VARCHAR(255) NOT NULL,
  seo_title VARCHAR(255) NOT NULL,
  meta_description VARCHAR(500),
  keywords TEXT,
  distance VARCHAR(60),
  travel_time VARCHAR(60),
  starting_fare VARCHAR(60),
  canonical_url VARCHAR(500),
  hero_image_path VARCHAR(190),
  intro_html MEDIUMTEXT,
  body_html MEDIUMTEXT,
  fare_table_html MEDIUMTEXT,
  faq_html MEDIUMTEXT,
  head_scripts MEDIUMTEXT,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  is_published BOOLEAN NOT NULL DEFAULT FALSE,
  created_by BIGINT UNSIGNED,
  updated_by BIGINT UNSIGNED,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_route_seo_city_slug(city_slug, slug),
  INDEX ix_route_seo_public(is_published, is_active, city_slug),
  INDEX ix_route_seo_company(company_id, updated_at),
  CONSTRAINT fk_route_seo_company FOREIGN KEY(company_id) REFERENCES companies(id) ON DELETE RESTRICT,
  CONSTRAINT fk_route_seo_created FOREIGN KEY(created_by) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT fk_route_seo_updated FOREIGN KEY(updated_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
CREATE TABLE IF NOT EXISTS blog_articles (
  id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
  company_id BIGINT UNSIGNED NOT NULL,
  title VARCHAR(255) NOT NULL,
  slug VARCHAR(190) NOT NULL,
  seo_title VARCHAR(255) NOT NULL,
  meta_description VARCHAR(500),
  keywords TEXT,
  canonical_url VARCHAR(500),
  hero_image_path VARCHAR(190),
  body_html MEDIUMTEXT,
  closing_html MEDIUMTEXT,
  head_scripts MEDIUMTEXT,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  is_published BOOLEAN NOT NULL DEFAULT FALSE,
  published_at TIMESTAMP NULL DEFAULT NULL,
  created_by BIGINT UNSIGNED,
  updated_by BIGINT UNSIGNED,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_blog_slug(slug),
  INDEX ix_blog_public(is_published, is_active, published_at),
  INDEX ix_blog_company(company_id, updated_at),
  CONSTRAINT fk_blog_company FOREIGN KEY(company_id) REFERENCES companies(id) ON DELETE RESTRICT,
  CONSTRAINT fk_blog_created FOREIGN KEY(created_by) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT fk_blog_updated FOREIGN KEY(updated_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
